#!/usr/bin/env python3
"""model_gen - writes new strategy modules as real Python files, versioned.

A generated model is a standalone module implementing:

    def signal(alert, votes):  -> (side, reason) or (None, "")

The generator takes a base family + a mutation (usually a Darwin diagnosis) and
emits `models/<family>_v<N>.py` whose *code* encodes the change — not just a
parameter tweak. Every generated file is compiled and smoke-tested before it is
registered, so a bad mutation can never reach the engine.

Registry: state/models.json  -> {version, models: [{name, module, family, gen,
                                                  diagnosis, born_ts, params}]}

    python3 model_gen.py --family flow --diagnosis BAD_ENTRY --gen 2
"""

import argparse
import json
import os
import time

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = os.path.join(HERE, "models")
STATE = os.path.join(HERE, "state")
REGISTRY = os.path.join(STATE, "models.json")

TEMPLATE = '''#!/usr/bin/env python3
"""Generated strategy — {doc}

family    : {family}
version   : v{version}
generation: {gen}
diagnosis : {diagnosis} ({why})
born      : {born}

Generated by model_gen.py. Do not hand-edit: a new mutation creates a new file.
"""

# tuned thresholds for this generation
MIN_TAKER   = {min_taker}      # taker-buy ratio needed to follow flow
MIN_BURST   = {min_burst}      # flow multiple vs baseline
MAX_RANGE   = {max_range}      # refuse to buy above this range position
MIN_RANGE   = {min_range}
AGREE       = {agree}          # model votes required
FADE        = {fade}           # True: trade against the alert, False: with it


def signal(alert, votes):
    """Return (side, reason). Never raises: the engine calls this per alert."""
    m = alert.get("metrics") or {{}}
    tbr = m.get("taker_buy_ratio")
    burst = m.get("burst_multiple") or 0
    rp = m.get("range_position")
    kind = alert.get("kind")
    net = sum(votes.values()) if votes else 0

    if burst < MIN_BURST:
        return None, ""
    if tbr is None or rp is None:
        return None, ""

    long_flow = tbr >= MIN_TAKER
    short_flow = tbr <= (1.0 - MIN_TAKER)
    agree_long = net >= AGREE
    agree_short = net <= -AGREE

    if FADE:
        # fade the extreme: the crowd is wrong at the edge of the range
        if kind == "PUMP" and rp >= MAX_RANGE and long_flow:
            return "sell", "fade pump rp=%.0f%% taker=%.0f%% x%.1f" % (100*rp, 100*tbr, burst)
        if kind == "DUMP" and rp <= MIN_RANGE and short_flow:
            return "buy", "fade dump rp=%.0f%% taker=%.0f%% x%.1f" % (100*rp, 100*tbr, burst)
        return None, ""

    if kind == "PUMP" and long_flow and agree_long and rp <= MAX_RANGE:
        return "buy", "flow+models rp=%.0f%% taker=%.0f%% x%.1f net=%+d" % (
            100*rp, 100*tbr, burst, net)
    if kind == "DUMP" and short_flow and agree_short and rp >= MIN_RANGE:
        return "sell", "flow+models rp=%.0f%% taker=%.0f%% x%.1f net=%+d" % (
            100*rp, 100*tbr, burst, net)
    return None, ""
'''

# how each diagnosis rewrites the generated code
MUTATIONS = {
    "BAD_ENTRY":   {"min_taker": 0.72, "min_burst": 4.0, "agree": 2, "doc": "stricter entry"},
    "FEE_BLEED":   {"min_taker": 0.66, "min_burst": 5.0, "agree": 3, "doc": "fewer, bigger moves"},
    "LEAKED":      {"fade": True, "max_range": 0.90, "min_taker": 0.70,
                    "doc": "fade extensions instead of chasing"},
    "OVERTRADING": {"min_burst": 6.0, "agree": 3, "doc": "rarer, higher quality"},
    "STOPPED_OUT": {"min_taker": 0.65, "min_burst": 3.0, "agree": 1,
                    "doc": "looser entries inside the noise"},
    "OUTSIDE":     {"doc": "unchanged family, fresh draw"},
}
DEFAULTS = {"min_taker": 0.70, "min_burst": 3.0, "max_range": 0.95, "min_range": 0.05,
            "agree": 2, "fade": False, "doc": "baseline"}


def load_registry():
    try:
        with open(REGISTRY) as fh:
            return json.load(fh)
    except Exception:
        return {"version": 0, "models": []}


def save_registry(reg):
    os.makedirs(STATE, exist_ok=True)
    tmp = REGISTRY + ".t"
    with open(tmp, "w") as fh:
        json.dump(reg, fh, indent=1)
    os.replace(tmp, REGISTRY)


def next_version(reg, family):
    return 1 + max([m["version"] for m in reg["models"] if m["family"] == family] + [0])


def generate(family, diagnosis, gen, why, params=None):
    """Write, compile, smoke-test and register a new model file."""
    reg = load_registry()
    version = next_version(reg, family)
    p = dict(DEFAULTS)
    p.update({k: v for k, v in MUTATIONS.get(diagnosis, {}).items() if k != "doc"})
    if params:
        p.update(params)
    p["doc"] = MUTATIONS.get(diagnosis, {}).get("doc", DEFAULTS["doc"])

    name = "%s_v%d" % (family, version)
    src = TEMPLATE.format(family=family, version=version, gen=gen, diagnosis=diagnosis,
                          why=why, born=time.strftime("%Y-%m-%d %H:%M:%S"),
                          min_taker=p["min_taker"], min_burst=p["min_burst"],
                          max_range=p["max_range"], min_range=p["min_range"],
                          agree=int(p["agree"]), fade=bool(p["fade"]), doc=p["doc"])
    os.makedirs(MODELS, exist_ok=True)
    path = os.path.join(MODELS, name + ".py")
    with open(path, "w") as fh:
        fh.write(src)

    # compile + smoke test before it can reach the engine
    compile(src, path, "exec")
    ns = {}
    exec(compile(src, path, "exec"), ns)
    fn = ns.get("signal")
    if not callable(fn):
        raise RuntimeError("generated module has no signal()")
    probe = {"kind": "PUMP", "metrics": {"taker_buy_ratio": 0.85, "burst_multiple": 9,
                                         "range_position": 0.93}}
    fn(probe, {"a": 1, "b": 1, "c": 1})
    fn({}, {})

    rec = {"name": name, "module": os.path.relpath(path, HERE), "family": family,
           "version": version, "generation": gen, "diagnosis": diagnosis,
           "why": why, "born_ts": int(time.time() * 1000),
           "params": {k: v for k, v in p.items() if k != "doc"}}
    reg["models"].append(rec)
    reg["version"] = reg.get("version", 0) + 1
    save_registry(reg)
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--family", default="flow")
    ap.add_argument("--diagnosis", default="BASELINE")
    ap.add_argument("--gen", type=int, default=1)
    ap.add_argument("--why", default="manual generation")
    args = ap.parse_args()
    rec = generate(args.family, args.diagnosis, args.gen, args.why)
    print(json.dumps(rec, indent=1))


if __name__ == "__main__":
    main()
