/**
 * Captures the live payloads the render smoke test asserts against.
 *
 * The test must check the *real* server's shapes — that is how the three missing
 * features were caught — so a small script fetches them and writes a TypeScript
 * module the bundled test can import. Run before `smoke.mjs`; if the backend is
 * unreachable the previous capture is kept, so the test still runs offline.
 *
 *   node scripts/capture-live.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const base = process.env.PUMPDUMP_API ?? 'http://127.0.0.1:8787';

const targets = [
  { name: 'LIVE_FLOW_SPLIT', url: `${base}/api/flow?split=1&limit=25` },
  { name: 'LIVE_OUTLOOK', url: `${base}/api/outlook?symbol=DOTUSDT` },
  { name: 'LIVE_FLOW_HISTORY', url: `${base}/api/flow/history?symbol=BTCUSDT&limit=360` },
];

const parts = [
  '/* GENERATED by scripts/capture-live.mjs — live payloads from the running backend.',
  '   Do not edit by hand; re-run the script instead. */',
  '',
];
let captured = 0;

for (const target of targets) {
  try {
    const res = await fetch(target.url, { headers: { accept: 'application/json' } });
    if (!res.ok) throw new Error(`http ${res.status}`);
    const body = await res.json();
    parts.push(`export const ${target.name} = ${JSON.stringify(body)} as const;`, '');
    captured += 1;
  } catch (error) {
    // Keep the test runnable offline: an empty object still exercises the
    // "no data" paths rather than failing the build.
    parts.push(`export const ${target.name} = {} as const;`);
    parts.push(`/* capture failed: ${String(error).slice(0, 120)} */`, '');
  }
}

writeFileSync(resolve(root, 'scripts', 'livePayloads.ts'), parts.join('\n'), 'utf8');
console.log(`capture-live: ${captured}/${targets.length} payloads -> scripts/livePayloads.ts`);
