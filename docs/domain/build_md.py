#!/usr/bin/env python3
"""Render DOMAIN-MODEL.md from content.py."""
import os
import content

HERE = os.path.dirname(os.path.abspath(__file__))
out = ["# " + content.TITLE, "", "*" + content.SUBTITLE + "*", "", content.BLURB, ""]

out.append("## Contents")
out.append("")
for i, s in enumerate(content.SECTIONS, 1):
    out.append("%d. [%s](#%s)" % (i, s["title"], s["id"]))
out.append("")

for s in content.SECTIONS:
    out.append("---")
    out.append("")
    out.append("## " + s["title"])
    out.append("")
    if s.get("figure"):
        name, caption = s["figure"]
        out.append("![%s](fig/%s)" % (caption, name))
        out.append("")
        out.append("*%s*" % caption)
        out.append("")
    for para in s.get("body", []):
        out.append(para)
        out.append("")
    if s.get("bullets"):
        for b in s["bullets"]:
            out.append("- " + b)
        out.append("")
    if s.get("table"):
        head, rows = s["table"]
        out.append("| " + " | ".join(head) + " |")
        out.append("|" + "|".join(["---"] * len(head)) + "|")
        for r in rows:
            out.append("| " + " | ".join(r) + " |")
        out.append("")
    for para in s.get("body2", []):
        out.append(para)
        out.append("")

out.append("---")
out.append("")
out.append("*Figures are generated by `docs/domain/diagrams.py` and rendered by "
           "`docs/domain/render_figs.py`; this document and its PDF are built from "
           "`docs/domain/content.py`, so they cannot disagree.*")
out.append("")

path = os.path.join(HERE, "DOMAIN-MODEL.md")
with open(path, "w") as fh:
    fh.write("\n".join(out))
print("wrote", path, len("\n".join(out)), "bytes")
